export const getBlogBySlug = (slug) => blogPosts.find(post => post.slug === slug);

/**
 * Helper to get related posts (same category, excluding current)
 */
export const getRelatedPosts = (currentSlug, limit = 3) => {
  const currentPost = getBlogBySlug(currentSlug);
  if (!currentPost) return blogPosts.slice(0, limit);

  const sameCategoryPosts = blogPosts.filter(
    post => post.category === currentPost.category && post.slug !== currentSlug
  );

  const otherPosts = blogPosts.filter(
    post => post.category !== currentPost.category && post.slug !== currentSlug
  );

  return [...sameCategoryPosts, ...otherPosts].slice(0, limit);
};

